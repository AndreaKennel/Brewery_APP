CREATE TABLE beer (
    beer_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    name         VARCHAR2(100) NOT NULL,
    style        VARCHAR2(50),
    abv          NUMBER(4,2),
    PRIMARY KEY (beer_id)
);

CREATE TABLE recipe (
    recipe_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    beer_id        NUMBER NOT NULL,
    batch_size     VARCHAR2(20),
    yeast          VARCHAR2(50),
    ibu            NUMBER,
    boil_time      VARCHAR2(20),
    fermentation   VARCHAR2(100),

    PRIMARY KEY (recipe_id),

    CONSTRAINT fk_recipe_beer
        FOREIGN KEY (beer_id)
        REFERENCES beer (beer_id),

    CONSTRAINT uq_recipe_beer
        UNIQUE (beer_id)
);

CREATE TABLE malt (
    malt_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    recipe_id     NUMBER NOT NULL,
    name          VARCHAR2(100),
    amount_kg     NUMBER(5,2),

    PRIMARY KEY (malt_id),

    CONSTRAINT fk_malt_recipe
        FOREIGN KEY (recipe_id)
        REFERENCES recipe(recipe_id)
);

CREATE TABLE hop (
    hop_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    recipe_id     NUMBER NOT NULL,
    name          VARCHAR2(100),
    amount_g      NUMBER,
    minutes       NUMBER,

    PRIMARY KEY (hop_id),

    CONSTRAINT fk_hop_recipe
        FOREIGN KEY (recipe_id)
        REFERENCES recipe(recipe_id)
);

