/*
DROP TABLE hop;
DROP TABLE malt;
DROP TABLE beer;
*/
CREATE TABLE beer_recipe (
    beer_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    name         VARCHAR2(100) NOT NULL,
    style        VARCHAR2(50),
    abv          NUMBER(4,2),
    batch_size     VARCHAR2(20),
    yeast          VARCHAR2(50),
    ibu            NUMBER,
    boil_time      VARCHAR2(20),
    fermentation   VARCHAR2(100),
    PRIMARY KEY (beer_id)
);

CREATE TABLE malt (
    malt_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    beer_id       NUMBER NOT NULL,
    name          VARCHAR2(100),
    amount_kg     NUMBER(5,2),

    PRIMARY KEY (malt_id),

    CONSTRAINT fk_malt_recipe
        FOREIGN KEY (beer_id)
        REFERENCES beer_recipe(beer_id)
);

CREATE TABLE hops (
    hop_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    beer_id       NUMBER NOT NULL,
    name          VARCHAR2(100),
    amount_g      NUMBER,
    minutes       NUMBER,

    PRIMARY KEY (hop_id),

    CONSTRAINT fk_hop_recipe
        FOREIGN KEY (beer_id)
        REFERENCES beer_recipe(beer_id)
);

CREATE OR REPLACE JSON RELATIONAL DUALITY VIEW beer_dv AS
beer_recipe @insert @update @delete
{
    _id   : beer_id,
    name  : name,
    style : style,
    abv   : abv,
    recipe :
    recipe
    {
        batchSize     : batch_size,
        yeast         : yeast,
        ibu           : ibu,
        boilTime      : boil_time,
        fermentation  : fermentation
        malt @insert @update @delete
        [
            {
                _id      : malt_id,
                name     : name,
                amountKg : amount_kg
            }
        ],

        hop @insert @update @delete
        [
            {
                _id      : hop_id,
                name     : name,
                amountG  : amount_g,
                minutes  : minutes
            }
        ]
    }
};

CREATE OR REPLACE JSON RELATIONAL DUALITY VIEW beer_dv AS
beer_recipe @insert @update @delete
{
    _id   : beer_id,
    name  : name,
    style : style,
    abv   : abv,
    recipe :
    recipe
    {
        batchSize     : batch_size,
