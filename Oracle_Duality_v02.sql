CREATE OR REPLACE JSON RELATIONAL DUALITY VIEW beer_dv AS
SELECT JSON
{
    '_id'  : b.beer_id,
    'name' : b.name,
    'style': b.style,
    'abv'  : b.abv,
    'recipe' :
    {
        'batchSize'    : b.batch_size,
        'hops' :
        	[ SELECT JSON { 'name' : h.name,
                        	'amountG'     : h.minutes,
                            'minutes'   : h.amount_g}
              FROM hops h WITH INSERT UPDATE DELETE
              WHERE h.beer_id = b.beer_id ],
        'yeast'        : b.yeast,
        'ibu'          : b.ibu,
        'boilTime'     : b.boil_time,
        'fermentation' : b.fermentation
    }
}
FROM beer_recipe b
WITH INSERT UPDATE DELETE;


